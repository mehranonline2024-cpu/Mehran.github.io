const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(`${__dirname}/../order/i18n.js`,'utf8');
const label={nodeType:3,nodeValue:'Afhalen'};
const placeholder={nodeType:1,childNodes:[],attrs:{placeholder:'Jouw naam'},hasAttribute(k){return k in this.attrs},getAttribute(k){return this.attrs[k]},setAttribute(k,v){this.attrs[k]=v}};
const body={nodeType:1,childNodes:[label,placeholder],hasAttribute(){return false}};
const button={textContent:'EN',attrs:{},setAttribute(k,v){this.attrs[k]=v}};
const document={body,documentElement:{lang:'nl'},getElementById:id=>id==='languageToggle'?button:null};
const context=vm.createContext({document,localStorage:{value:null,getItem(){return this.value},setItem(_k,v){this.value=v}},Node:{TEXT_NODE:3,ELEMENT_NODE:1},MutationObserver:class{observe(){}},CustomEvent:class{constructor(type,init){this.type=type;this.detail=init.detail}},window:{addEventListener(){},dispatchEvent(){}},setTimeout(){}});
vm.runInContext(source,context);
context.window.gtSetLanguage('en');
assert.equal(document.documentElement.lang,'en');
assert.equal(button.textContent,'NL');
assert.equal(label.nodeValue,'Pick-up');
assert.equal(placeholder.attrs.placeholder,'Your name');
assert.equal(context.window.gtTranslateValue('Geschatte bezorgtijd: 25–45 minuten.'),'Estimated delivery time: 25–45 minutes.');
context.window.gtSetLanguage('nl');
assert.equal(document.documentElement.lang,'nl');
assert.equal(button.textContent,'EN');
assert.equal(label.nodeValue,'Afhalen');
assert.equal(placeholder.attrs.placeholder,'Jouw naam');
console.log('PASS: language toggle translates page text and fields to English and restores Dutch.');
