const assert=require('node:assert/strict');
const {verified,describe,html,disclosure}=require('../assets/allergens.js');
assert.equal(verified({}),false);
assert.match(describe({}),/Nog niet gecontroleerd/);
assert.match(describe({allergens_contains:[]}),/Nog niet gecontroleerd/);
assert.match(describe({allergens_contains:['milk'],allergens_may_contain:[],allergens_verified_at:null}),/Nog niet gecontroleerd/);
const checked={allergens_contains:['wheat','milk'],allergens_may_contain:['sesame'],allergens_verified_at:'2026-10-06T10:00:00Z'};
assert.equal(verified(checked),true);
assert.match(describe(checked),/Tarwe \(gluten\), Melk/);
assert.match(describe(checked),/Kan bevatten: Sesam/);
assert.match(describe(checked,'en'),/Contains: Wheat \(gluten\), Milk/);
assert.match(describe(checked,'en'),/May contain: Sesame/);
assert.equal(verified({...checked,allergens_contains:['bogus']}),false);
assert.match(describe({...checked,allergens_contains:[],allergens_may_contain:[]},'en'),/reported as an ingredient/);
assert.doesNotMatch(html({...checked,name:'<script>alert(1)</script>'}),/<script>/);
assert.equal(html({},'en',true),'');
assert.equal(html({},'nl',true),'');
assert.match(html({},'en'),/Food allergy\?/);
assert.match(html({},'nl'),/allergeneninformatie/);
assert.doesNotMatch(html({},'nl'),/Nog niet gecontroleerd/);
assert.match(html(checked,'nl',true),/Tarwe \(gluten\), Melk/);
const sauce={label:'Cocktail',allergens_contains:['eggs'],allergens_may_contain:['mustard'],allergens_verified_at:checked.allergens_verified_at};
const info=disclosure({},[{title:'Sauzen',values:[sauce]}]);
assert.match(info,/^<details class="product-allergens"><summary>Allergeneninformatie<\/summary>/);
assert.doesNotMatch(info,/<details[^>]*\sopen(?:\s|=|>)/);
assert.match(info,/Bevat: Eieren\. Kan bevatten: Mosterd/);
assert.match(info,/allergeneninformatie of neem vóór het bestellen contact op/);
assert.doesNotMatch(info,/<input|<select|data-group=/);
assert.doesNotMatch(info,/Geen van de 14/);
const english=disclosure(checked,[{title:'Sauzen',values:[sauce]}],'en',s=>s==='Sauzen'?'Sauces':s);
assert.match(english,/<summary>Allergen information<\/summary>/);
assert.match(english,/<h5>Sauces<\/h5>/);
assert.match(english,/Contains: Eggs\. May contain: Mustard/);
const unsafe=disclosure({},[{title:'<script>unsafe</script>',values:[{...sauce,label:'<img src=x>'}]}]);
assert.doesNotMatch(unsafe,/<script|<img/);
assert.doesNotMatch(describe({...sauce,allergens_contains:[]}),/\.\./);
console.log('Verified allergen disclosure, escaping and unknown-state tests passed');
